namespace Aquila.Core.Queries;

/// <summary>
/// Specifies the sorting direction (Ascending or Descending) for query results.
/// </summary>
public enum SortOrder
{
    /// <summary>
    /// Sort items in ascending order (smallest to largest / A to Z).
    /// </summary>
    Ascending,

    /// <summary>
    /// Sort items in descending order (largest to smallest / Z to A).
    /// </summary>
    Descending
}
